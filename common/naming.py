"""Naming conventions and S3 path helpers.

Isolation layer 3 in the blog ("Adapter naming convention") requires that every
adapter inference component name encodes the tenant id, task, and version. All
components and S3 keys generated by this package go through the helpers in this
module so the convention is enforced in one place.
"""

from __future__ import annotations

import re
from typing import Union

from multi_tenant_lora_sagemaker.config.schemas import PlatformConfig

# SageMaker limits resource names to 63 characters, alphanumeric + hyphen.
_SM_NAME_RE = re.compile(r"^[a-zA-Z0-9][a-zA-Z0-9-]{0,62}$")


def _check_name(value: str, label: str) -> str:
    if not _SM_NAME_RE.match(value):
        raise ValueError(
            f"{label} {value!r} is not a valid SageMaker resource name "
            "(alphanumeric + hyphen, max 63 chars)"
        )
    return value


def adapter_component_name(tenant_id: str, task: str, version: Union[int, str]) -> str:
    """Return the adapter inference component name: ``{tenant}-{task}-v{version}``."""
    name = f"{tenant_id}-{task}-v{version}"
    return _check_name(name, "adapter component name")


def training_job_name(tenant_id: str, task: str, version: Union[int, str]) -> str:
    """Return the training job name: ``{tenant}-{task}-v{version}-train``."""
    name = f"{tenant_id}-{task}-v{version}-train"
    return _check_name(name, "training job name")


# ----- S3 path helpers ------------------------------------------------------


def _s3_uri(bucket: str, key: str) -> str:
    return f"s3://{bucket}/{key.lstrip('/')}"


def training_data_s3_uri(
    platform: PlatformConfig, tenant_id: str, task: str
) -> str:
    """``s3://{bucket}/{tenant_id}/training-data/{task}/``."""
    return _s3_uri(platform.data_bucket, f"{tenant_id}/training-data/{task}/")


def evaluation_data_s3_uri(
    platform: PlatformConfig, tenant_id: str, evaluation_data_s3_key: str
) -> str:
    """``s3://{bucket}/{tenant_id}/evaluation-data/{key}``."""
    key = evaluation_data_s3_key.lstrip("/")
    return _s3_uri(platform.data_bucket, f"{tenant_id}/evaluation-data/{key}")


def adapter_s3_prefix(
    platform: PlatformConfig,
    tenant_id: str,
    task: str,
    version: Union[int, str],
) -> str:
    """``s3://{bucket}/{tenant_id}/adapters/{task}/v{version}/``."""
    return _s3_uri(
        platform.data_bucket, f"{tenant_id}/adapters/{task}/v{version}/"
    )


def training_output_s3_uri(
    platform: PlatformConfig,
    tenant_id: str,
    task: str,
    version: Union[int, str],
) -> str:
    """S3 output path passed as ``OutputDataConfig.S3OutputPath`` for a training job."""
    # SageMaker appends ``{JobName}/output/`` to this prefix automatically.
    return _s3_uri(
        platform.data_bucket, f"{tenant_id}/training-output/{task}/v{version}/"
    )


def adapter_tarball_s3_uri(
    platform: PlatformConfig,
    tenant_id: str,
    task: str,
    version: Union[int, str],
) -> str:
    """S3 URI to the packaged ``adapter.tar.gz`` consumed by the adapter inference component."""
    return f"{adapter_s3_prefix(platform, tenant_id, task, version)}adapter.tar.gz"


def base_model_s3_uri(platform: PlatformConfig, base_model_relative_path: str) -> str:
    """S3 URI to the shared read-only base model weights."""
    rel = base_model_relative_path.lstrip("/")
    return _s3_uri(
        platform.data_bucket, f"{platform.base_model_prefix}/{rel}"
    )
